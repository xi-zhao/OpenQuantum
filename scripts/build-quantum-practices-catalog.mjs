import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";
import manifest from "../src/quantum-practices/upstream/source.json" with { type: "json" };
import { skills } from "../src/quantum-practices/upstream/generated/skill-catalog.js";

// No network or upstream code execution. The maintainer first reviews and pins each source digest.
const root = fileURLToPath(new URL("../src/quantum-practices/upstream/", import.meta.url));
const [flag, snapshot, ...extra] = process.argv.slice(2);
assert.ok(!extra.length && (flag === "--check" && !snapshot || flag === "--source" && snapshot),
  "Usage: node scripts/build-quantum-practices-catalog.mjs --check | --source /path/to/pinned/quantum-skills");
const digest = value => createHash("sha256").update(value).digest("hex");
const byId = new Map(skills.map(skill => [skill.id, skill]));
const rebuilt = [];
for (const guide of manifest.guides) {
  assert.match(guide.path, /^(?:[a-z0-9-]+\/)*SKILL\.md$/);
  const content = flag === "--source"
    ? await readFile(path.join(snapshot, guide.path), "utf8")
    : byId.get(guide.id)?.content;
  assert.equal(typeof content, "string", guide.id);
  assert.equal(digest(content), guide.sha256, `${guide.path}: content differs from the pinned guide`);
  const frontmatter = content.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/)?.[1];
  assert.ok(frontmatter, `${guide.id}: missing frontmatter`);
  const { name, description } = YAML.parse(frontmatter);
  assert.equal(typeof name, "string");
  assert.equal(typeof description, "string");
  rebuilt.push({ id: guide.id, name, description, content });
}
assert.equal(new Set(rebuilt.map(skill => skill.id)).size, manifest.catalogEntries);
if (flag === "--source") {
  const guidePaths = (await readdir(snapshot, { recursive: true })).filter(p => path.basename(p) === "SKILL.md").map(p => p.split(path.sep).join("/")).sort();
  assert.deepEqual(guidePaths, manifest.guides.map(guide => guide.path).sort(), "Snapshot guide inventory differs from manifest");
}
const code = "// Generated by scripts/build-quantum-practices-catalog.mjs from pinned MIT guides.\n"
  + `export const skills = ${JSON.stringify(rebuilt, null, 4)};\n`;
const catalogPath = path.join(root, "generated/skill-catalog.js");
if (flag === "--check") {
  assert.equal(await readFile(catalogPath, "utf8"), code);
  assert.equal(digest(code), manifest.files.find(file => file.path === "generated/skill-catalog.js").sha256);
} else {
  await writeFile(catalogPath, code);
  manifest.files.find(file => file.path === "generated/skill-catalog.js").sha256 = digest(code);
  await writeFile(path.join(root, "source.json"), JSON.stringify(manifest, null, 2) + "\n");
}
console.log(`Verified ${rebuilt.length} guides at ${manifest.corpusCommit}`);
